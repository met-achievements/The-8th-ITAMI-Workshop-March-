import qrcode from './vendor/qrcode.mjs';
import { UPLOAD_URL } from './config.mjs';
import { createTicket,parseTicket,ticketUrl,validateTicket,encryptPhoto } from './tickets.mjs';
import { preparePhoto,downloadFile } from './media.mjs';
const base=new URL('./',location.href),$=id=>document.getElementById(id);
let tickets=[],selectedPhoto=null,photoGeneration=0,preparedTicket=null,exported=false;
const showError=(id,e)=>{const el=$(id);el.textContent=e.message||String(e);el.hidden=false;};
function selectTab(name){['print','upload'].forEach(n=>{$('tab-'+n).setAttribute('aria-selected',String(n===name));$('panel-'+n).hidden=n!==name;});}
$('tab-print').addEventListener('click',()=>selectTab('print'));
$('tab-upload').addEventListener('click',()=>selectTab('upload'));
document.querySelector('[role="tablist"]').addEventListener('keydown',e=>{if(['ArrowLeft','ArrowRight'].includes(e.key)){e.preventDefault();const name=$('panel-print').hidden?'print':'upload';selectTab(name);$('tab-'+name).focus();}});
function svgQr(text){
  const qr=qrcode(0,'M');qr.addData(text,'Byte');qr.make();
  return qr.createSvgTag({cellSize:3,margin:12,scalable:true});
}
function renderTickets(){
  const grid=$('ticket-grid');grid.replaceChildren();
  tickets.forEach(ticket=>{
    const card=document.createElement('article');card.className='ticket';
    const heading=document.createElement('div');heading.className='ticket-heading';
    const brand=document.createElement('span');brand.textContent='CHRISTMAS MEMORIES';
    const number=document.createElement('strong');number.textContent='No. '+ticket.number;heading.append(brand,number);
    const graphics=document.createElement('div');graphics.className='ticket-graphics';
    const qrFigure=document.createElement('figure');
    // The QR library emits markup from an ASCII URL generated by this application.
    qrFigure.innerHTML=svgQr(ticketUrl(ticket,base));
    qrFigure.querySelector('svg').setAttribute('aria-label','写真を開くQRコード');qrFigure.querySelector('svg').setAttribute('role','img');
    const qrCaption=document.createElement('figcaption');qrCaption.textContent='① QRを読み込んでページを開く';qrFigure.append(qrCaption);
    const markerFigure=document.createElement('figure'),marker=document.createElement('img');marker.src='hiro.png';marker.alt='ARでかざすHiroマーカー';
    const markerCaption=document.createElement('figcaption');markerCaption.textContent='② ARで見る → こちらにかざす';markerFigure.append(marker,markerCaption);graphics.append(qrFigure,markerFigure);
    const copy=document.createElement('div');copy.className='ticket-copy';copy.textContent='あなたの写真に、小さな雪が降る。\n台紙は折らずに、大切にお持ち帰りください。';copy.style.whiteSpace='pre-line';
    const link=document.createElement('a');link.className='ticket-link';link.href=ticketUrl(ticket,base);link.target='_blank';link.rel='noopener noreferrer';link.textContent='このQRを開く ↗';
    card.append(heading,graphics,copy,link);grid.append(card);
  });
  $('print-tickets').disabled=!tickets.length;$('save-tickets').disabled=!tickets.length;
  $('print-status').textContent=tickets.length+'組分を作成しました。印刷前に管理リストを保存してください。';
}
$('generate-tickets').addEventListener('click',()=>{
  $('print-error').hidden=true;
  try{
    const count=Number($('ticket-count').value),start=Number($('start-number').value);
    if(!Number.isInteger(count)||count<1||count>60||!Number.isInteger(start)||start<1||start+count-1>99999)throw new Error('枚数は1〜60、受付番号は1〜99999で入力してください。');
    if(tickets.length&&!exported){showError('print-error',new Error('作成済みの管理リストを保存してから、次のQRを作成してください。'));return;}
    tickets=Array.from({length:count},(_,i)=>createTicket(start+i));exported=false;renderTickets();
  }catch(e){showError('print-error',e);}
});
$('print-tickets').addEventListener('click',()=>{
  if(!exported){showError('print-error',new Error('印刷前に「管理リストを保存」を押してください。'));return;}
  window.print();
});
$('save-tickets').addEventListener('click',()=>{
  const record={version:1,baseUrl:base.href,createdAt:new Date().toISOString(),tickets};
  downloadFile(new Blob([JSON.stringify(record,null,2)],{type:'application/json'}),'snow-globe-tickets-'+Date.now()+'.json');exported=true;
  $('print-error').hidden=true;$('print-status').textContent='管理リストを保存しました。QRを印刷できます。';
});
$('import-tickets').addEventListener('change',async e=>{
  $('print-error').hidden=true;
  try{
    const file=e.target.files[0];if(!file)return;if(file.size>100000)throw new Error('管理リストのサイズが大きすぎます。');
    const data=JSON.parse(await file.text());
    if(data.version!==1||!Array.isArray(data.tickets)||!data.tickets.length||data.tickets.length>60)throw new Error('管理リストを読み込めません。');
    // Never silently re-issue preprinted tickets at a different origin/path.
    if(new URL(data.baseUrl).href!==base.href)throw new Error('このリストは別のURLで作成されています。作成時と同じスタッフページで開いてください。');
    tickets=data.tickets.map(t=>{validateTicket(t);return{id:t.id,key:t.key,number:String(t.number||'').slice(0,12)};});
    if(new Set(tickets.map(t=>t.id)).size!==tickets.length)throw new Error('IDが重複している管理リストです。');
    renderTickets();exported=true;$('print-status').textContent='管理リストを復元しました。同じQRを再印刷できます。';
  }catch(e){showError('print-error',e);}finally{e.target.value='';}
});
function resetResult(){
  $('upload-result').hidden=true;$('upload-status').textContent='';$('upload-error').hidden=true;
}
function updateUploadTarget(){
  resetResult();preparedTicket=null;
  try{preparedTicket=parseTicket($('ticket-url').value,base);$('ticket-status').textContent='登録先：'+(preparedTicket.number?'No. '+preparedTicket.number:preparedTicket.id);}
  catch{$('ticket-status').textContent='有効なQRのURLを入力してください。';}
  $('export-photo').disabled=!preparedTicket||!selectedPhoto;
}
$('ticket-url').addEventListener('input',updateUploadTarget);
$('registration-photo').addEventListener('change',async e=>{
  const generation=++photoGeneration;selectedPhoto=null;$('export-photo').disabled=true;resetResult();
  $('photo-thumbnail').hidden=true;$('thumbnail-empty').hidden=false;
  try{const file=e.target.files[0];if(!file)return;
    const photo=await preparePhoto(file);if(generation!==photoGeneration)return;
    selectedPhoto=photo;$('photo-thumbnail').src=photo.dataUrl;$('photo-thumbnail').hidden=false;$('thumbnail-empty').hidden=true;
    $('upload-status').textContent='写真を選びました。登録先を確認して保存してください。';
  }catch(e){showError('upload-error',e);}finally{if(generation===photoGeneration)$('export-photo').disabled=!preparedTicket||!selectedPhoto;}
});
$('export-photo').addEventListener('click',async()=>{
  if(!selectedPhoto||!preparedTicket)return;
  $('export-photo').disabled=true;$('upload-error').hidden=true;
  try{
    const ticket={...preparedTicket},photo=selectedPhoto;
    const record=await encryptPhoto(await photo.blob.arrayBuffer(),ticket);
    downloadFile(new Blob([JSON.stringify(record)],{type:'application/json'}),ticket.id+'.json');
    $('upload-status').textContent='登録ファイルを保存しました。次に「②」で、このファイルをGitHubへ追加してください。';
    $('check-photo').href=ticketUrl(ticket,base);$('upload-result').hidden=false;
  }catch(e){showError('upload-error',e);}finally{$('export-photo').disabled=!preparedTicket||!selectedPhoto;}
});
$('github-upload').href=UPLOAD_URL;
const initial=new URL(location.href);
if(initial.searchParams.has('id')){
  const target=new URL('./',base);target.search=initial.search;target.searchParams.delete('tab');target.hash=initial.hash;
  $('ticket-url').value=target.href;updateUploadTarget();selectTab('upload');
}else if(initial.searchParams.get('tab')==='upload'||initial.hash==='#upload')selectTab('upload');
